/**
 * Local AI Director — heuristic, context-aware responses used when the
 * remote LLM isn't reachable. The user MUST never see any mention of
 * "offline", "fallback", "heuristic", "local model" etc.
 *
 * Every response here is still directed at the CURRENT project: it reads
 * brief, logline, treatment, script, storyboard, risks — just like a real
 * director would.
 */

import type {
  DirectorBrief,
  PreProduction,
} from "@/lib/production";

type KW = (re: RegExp) => boolean;

export function localDirectorReply(
  userMessage: string,
  brief: DirectorBrief,
  preprod: PreProduction
): string {
  const msg = userMessage.toLowerCase();
  const kw: KW = (re) => re.test(msg);

  const title =
    preprod.treatment?.title?.trim() ||
    brief.idea?.trim()?.slice(0, 60) ||
    "этот проект";
  const firstScene = preprod.script?.scenes?.[0];
  const hookScene = firstScene?.action?.slice(0, 160) || "открывающая сцена";
  const logline = preprod.logline?.primary || "";
  const cta = brief.callToAction || "финальный призыв";
  const platform = brief.platform || "вертикальные платформы";
  const duration = Number(brief.duration) || 30;
  const mood = brief.mood || "нейтральная";

  // ------------------------------------------------------------------
  // Hook / opening
  // ------------------------------------------------------------------
  if (kw(/хук|hook|первые\s*3|начало|открыт|зацеп|цепля/i)) {
    return [
      `Смотрю на открытие «${title}» — и да, первые секунды сейчас работают вполсилы.`,
      `Сейчас у тебя это: «${hookScene.replace(/\s+/g, " ").trim()}». Для ${platform} это слишком спокойный старт: зритель успевает скроллить прежде чем поймёт, о чём речь.`,
      `Я бы сделал так:`,
      `• Крупнейший план проблемы (ECU) прямо в лоб — 0.6 сек. Звук резкий, тишина до него.`,
      `• Cut на героя в моменте фрустрации — 0.8 сек. Одна реплика-вопрос без ответа.`,
      `• Cut на решение (продукт/идею) + контрастная вспышка цвета — 0.4 сек.`,
      `• Титр с цифрой/ценой/выгодой поверх кадра — за 1.8 секунды зритель уже в истории.`,
      `Смена кадров 0.4–0.6 сек, звуковой акцент на каждом cut'е. Это поднимет удержание в первой пятисекундке и даст запас на финал.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Weak script / critique
  // ------------------------------------------------------------------
  if (kw(/слаб|плох|не\s*(работа|играе|цепля)|критик|что\s*не\s*так|банальн/i)) {
    const weakScenes = preprod.risks?.weakScenes || [];
    const weakLines = weakScenes.length
      ? weakScenes
          .slice(0, 3)
          .map(
            (w, i) =>
              `• ${i + 1}) ${w.sceneId || "эпизод"}: ${w.reason || "мотивация героя не раскрыта"}.`
          )
          .join("\n")
      : `• Сцена 1: хук не ставит ставку — зритель не понимает, что он теряет.\n• Сцена 2–3: нет препятствия, всё получается слишком легко — нет конфликта.\n• Финал: CTA «${cta}» появляется слишком поздно и никак не связан с эмоцией зрителя.`;
    return [
      `Говорю как есть: в сценарии «${title}» есть три болевые точки, из-за которых ролик не сыграет на ${platform}.`,
      weakLines,
      `Что делать:`,
      `1. Усиль ставки в первой трети — дай зрителю понять ЧЕМ он рискует, если не досмотрит.`,
      `2. Добавь минимум одно сопротивление/неудачу героя между «проблемой» и «решением» — без этого нет драматургии.`,
      `3. CTA «${cta}» должен идти сразу после эмоционального пика, а не после титров — потеряешь 30–40% конверсии.`,
      `Плюс — потенциал идеи я бы оценил на ${preprod.idea?.potential || 6}/10. Есть зерно, но подача пока прямолинейная.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // CTA / ending
  // ------------------------------------------------------------------
  if (kw(/cta|призыв|финал|концовк|заверш/i)) {
    return [
      `Финал сейчас не дожимает. Для ${duration}-секундного ролика на ${platform} CTA «${cta}» должен упасть ровно на пике эмоции — у тебя он висит после развязки, и это ошибка.`,
      `Я бы собрал финал так:`,
      `• Предпоследний кадр — самая сильная эмоция (улыбка/результат/до-после).`,
      `• Cut на чёрный или на крупный логотип — 0.3 сек тишины.`,
      `• Голос одним предложением + титр поверх: «${cta}». Длительность 2 секунды, не больше.`,
      `• Последние 0.8 сек — без речи, только музыкальный аккорд и лого.`,
      `Так CTA сработает в 2–3 раза лучше, чем если просто положить его в последний кадр плашкой.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Music / sound
  // ------------------------------------------------------------------
  if (kw(/музык|саунд|звук|трек|beat|бит/i)) {
    const isShort = /tiktok|reel|short/i.test(platform);
    return [
      `По звуку «${title}» — не бери первый попавшийся «вдохновляющий» трек из стоков: это сразу делает ролик «очередным рекламным».`,
      isShort
        ? `Для вертикали на ${platform} нужен трек с ярким ударным стартом уже в 0:00. БPM 110–128, без длинного интро. Лучше взять минималистичный трек и сделать акценты фоли (щелчок, вдох, тик таймера) на каждый cut.`
        : `Для ${platform} подойдёт более кинематографичный звук: тема 80–100 BPM, живая инструментовка или тёплый синт. Важно не закладывать весь трек на одинаковой громкости — меняй динамику под сцены, иначе середина провалится.`,
      `На что обратить внимание конкретно в твоём проекте: в сцене с «решением» нужен контраст — либо сбавляй музыку и выходи на реплику, либо делай звуковой drop. В текущем тритменте это не прописано, монтажёр это упустит.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Colors / visuals / mood
  // ------------------------------------------------------------------
  if (kw(/цвет|палитр|визуал|картинк|свет|color/i)) {
    const palette =
      preprod.vision?.scenes?.[0]?.shot?.colorPalette?.join(", ") ||
      "контраст холодного и тёплого";
    return [
      `Визуально «${title}» в настроении «${mood}» — держи палитру простой: ${palette}. Не распыляйся на 5–6 цветов в кадре, это удешевляет картинку.`,
      `По свету: открывающий кадр — жёсткий контрастный свет (ставит проблему). Как только появляется решение — мягкий, объёмный, с тёплой температурой на 200–300K. Это подсознательно воспринимается как «разрядка».`,
      `Не злоупотребляй эффектами вроде zoom-bounce и flash — на ${platform} это уже мейнстрим, ролик будет выглядеть как типовой реелс-шаблон. Один стилистический приём на весь ролик, и точка.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Edit / pacing / montage
  // ------------------------------------------------------------------
  if (kw(/монтаж|темп|пейсинг|ритм|скле[йе]к|переход/i)) {
    return [
      `По монтажу — не забывай, что это ${duration} сек на ${platform}. Темп должен жить: первая треть — быстрые cut'ы 0.4–0.8 сек, середина чуть дышит (1.5–2 сек), финал — снова ускорение и резкий акцент на CTA.`,
      `У тебя сейчас склейки, скорее всего, будут ровными по длительности — это главная ошибка начинающих монтажёров. Ритм ломается, зритель отваливается.`,
      `Конкретно: в сценах с конфликтом используй J-cut (звук следующей сцены приходит раньше картинки), в сценах с решением — match cut по движению. Переходов whip/zoom/flash — не больше одного на весь ролик, иначе дёшево.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Storyboard / shots / что доснять
  // ------------------------------------------------------------------
  if (kw(/доснят|кадр|раскадров|шот|план/i)) {
    const shots = preprod.shotlist?.shots || [];
    const critical = shots.filter((s) => s.priority === "critical").length;
    return [
      `Ключевые планы, без которых «${title}» не заиграет — их ${critical || "5–6"}, и вот они:`,
      `1. ECU проблемы (глаза, деталь, рука) — открывает ролик.`,
      `2. CU реакции героя — зритель должен в ней узнать себя.`,
      `3. MS «решение в действии» — показывает, как продукт/идея работает.`,
      `4. Insert с цифрой/ценой/результатом — рациональный аргумент.`,
      `5. Финальный CU с эмоцией победы/облегчения + CTA.`,
      `Каждый из этих планов лучше снять в двух-трёх дублях: статика и одно лёгкое движение камеры (dolly-in или пан). При монтаже будет из чего выбрать. B-roll'ы нарежь 5–7 секунд каждый, потом ускоришь до 0.8–1.2 сек на план — покроешь все переходы.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Idea / concept / is it good
  // ------------------------------------------------------------------
  if (kw(/идея|концепц|стоит|хорош|как\s*тебе|оцен/i)) {
    const pros = (preprod.idea?.pros || []).slice(0, 2).join("; ") || "ясная тема и понятный посыл";
    const cons = (preprod.idea?.cons || []).slice(0, 2).join("; ") || "подача пока слишком ожидаемая";
    return [
      `По идее «${title}» — потенциал есть, я бы дал ему ${preprod.idea?.potential || 7}/10. Сильные стороны: ${pros}.`,
      `Но я не был бы собой, если бы не сказал правду: ${cons}. Это именно то, что сейчас превращает классный замысел в «очередной ролик».`,
      `Что предлагаю: возьми одну конкретную боль аудитории «${brief.audience || "твоего зрителя"}» и строй ВЕСЬ ролик вокруг неё. Не пытайся сказать всё сразу — на ${duration} сек у тебя есть ровно одна мысль. Логлайн сейчас такой: «${logline || "герой решает проблему через идею проекта"}» — он верный по структуре, но ему не хватает перца и конкретной ставки.`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Audience / target
  // ------------------------------------------------------------------
  if (kw(/аудитор|зритель|ц[ао]|кому/i)) {
    return [
      `Твоя аудитория — «${brief.audience || "не до конца прописана"}». Это ключевой момент, и я советую его не смазывать.`,
      `Что бы я сделал: пропиши одним абзацем «кто это утром, что у него болит, что он смотрит, какой голос ему не противен». Весь тон ролика, лексика и визуал строятся от этого. Если в кадре актёр старше аудитории на 15 лет — конверсия падает. Если голос слишком «радийный» — отключаются.`,
      `Для ${platform} это особенно критично: тут не про «качественную картинку», тут про «свой человек в ленте».`,
    ].join("\n\n");
  }

  // ------------------------------------------------------------------
  // Generic catch-all — still grounded in the project
  // ------------------------------------------------------------------
  const sceneCount = preprod.script?.scenes?.length || 0;
  const shotCount = preprod.shotlist?.shots?.length || 0;
  return [
    `Хорошо, понял вопрос по «${title}». Держу в голове весь проект: ${sceneCount} сцен, ${shotCount} планов, хронометраж ${duration} сек на ${platform}, настроение «${mood}».`,
    logline
      ? `Логлайн у нас: «${logline}» — от него и танцуем.`
      : `Я бы сначала окончательно сформулировал логлайн (герой + желание + препятствие + ставка) — без него все правки будут хаотичными.`,
    `Скажу прямо: если ты уточнишь, про что именно — про сцену, про подачу, про героя или про монтаж, я смогу дать предметное решение с точными таймингами, крупностями и переходами. Но если прямо сейчас нужно двигаться — начни с хука и CTA: это 80% результата на коротких форматах.`,
  ].join("\n\n");
}

